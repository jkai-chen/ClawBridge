package dispatchermodel

import (
	"bytes"
	_ "embed"
	"encoding/json"
	"fmt"
	"slices"
	"strconv"
	"strings"
)

// ModelHint is one model the agent's pinned build can call with a listed
// provider, from that build's own catalogue (§11.1 step 2). Prices are the
// catalogue's list prices in US dollars per million tokens: a hint, not a
// quote.
type ModelHint struct {
	ID            string  `json:"id"`
	Name          string  `json:"name"`
	ContextWindow int     `json:"context_window"`
	InputPerMTok  float64 `json:"input_per_mtok"`
	OutputPerMTok float64 `json:"output_per_mtok"`
}

// models.json is generated by dispatcher-agent/scripts/write-models.ts from
// the pinned pi-ai; CI fails when it is out of date.
//
//go:embed models.json
var modelsJSON []byte

var modelHints = func() map[string][]ModelHint {
	var file struct {
		Version     int                    `json:"version"`
		Description string                 `json:"description"`
		Source      string                 `json:"source"`
		Models      map[string][]ModelHint `json:"models"`
	}
	dec := json.NewDecoder(bytes.NewReader(modelsJSON))
	dec.DisallowUnknownFields()
	if err := dec.Decode(&file); err != nil || file.Version != 1 {
		panic("dispatchermodel: models.json is not valid")
	}
	return file.Models
}()

// HintsShown is how many models setup lists for a provider.
const HintsShown = 10

// ModelHints returns the models setup lists for provider, cheapest first by
// list price, and how many more the catalogue has. Models with no listed
// price (free tiers and previews, often rate-limited) are left out of the
// list; any of them can still be typed. The custom provider has none.
func ModelHints(providerID string) (shown []ModelHint, more int) {
	var priced []ModelHint
	for _, m := range modelHints[providerID] {
		if m.InputPerMTok > 0 || m.OutputPerMTok > 0 {
			priced = append(priced, m)
		}
	}
	slices.SortStableFunc(priced, func(a, b ModelHint) int {
		if c := (a.InputPerMTok + a.OutputPerMTok) - (b.InputPerMTok + b.OutputPerMTok); c != 0 {
			if c < 0 {
				return -1
			}
			return 1
		}
		return strings.Compare(a.ID, b.ID)
	})
	more = len(modelHints[providerID])
	if len(priced) > HintsShown {
		priced = priced[:HintsShown]
	}
	return priced, more - len(priced)
}

// HintLine is one listed model, as both front ends print it.
func HintLine(m ModelHint) string {
	return fmt.Sprintf("%s (%s) · $%s in / $%s out per million tokens · %s context", m.Name, m.ID, price(m.InputPerMTok), price(m.OutputPerMTok), tokens(m.ContextWindow))
}

// HintsNote is the line under the list.
func HintsNote(more int) string {
	note := "List prices from the agent's catalogue, not a quote."
	if more > 0 {
		note = fmt.Sprintf("%d more in the catalogue: type any model ID. ", more) + note
	}
	return note
}

// ModelAnswer reads step 2's answer: a number picks that listed model, and
// anything else is the model ID itself. So a model whose ID is a small
// number can't be typed while the list is shown; no catalogue ID is one
// (R152-L2), and --model takes any ID.
func ModelAnswer(answer string, shown []ModelHint) string {
	if n, err := strconv.Atoi(answer); err == nil && n >= 1 && n <= len(shown) {
		return shown[n-1].ID
	}
	return answer
}

func price(v float64) string {
	return strconv.FormatFloat(v, 'f', -1, 64)
}

func tokens(n int) string {
	switch {
	case n >= 1_000_000 && n%1_000_000 == 0:
		return strconv.Itoa(n/1_000_000) + "M"
	case n >= 1000:
		return strconv.Itoa(n/1000) + "k"
	}
	return strconv.Itoa(n)
}

// SetModelHintsForTest replaces the hints, for another package's tests,
// and returns what restores them.
func SetModelHintsForTest(hints map[string][]ModelHint) (restore func()) {
	saved := modelHints
	modelHints = hints
	return func() { modelHints = saved }
}
